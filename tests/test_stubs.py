def test_render_tree_root_reexports_top_level_tools_only() -> None:
    """Top-level tools are re-exported so ``from tools import <name>`` works.
    Namespaced tools are not re-exported from the root — the model imports
    them via ``from tools.<namespace> import <name>``."""
    a = _SchemaTool("ping", description="Ping.", schema={"type": "object"})
    b = _SchemaTool("pong", description="Pong.", schema={"type": "object"})
    ns = _build([(a, None), (b, None)])
    files = stubs.render_tree(ns)
    paths = [f.path for f in files]
    assert "__init__.py" in paths
    assert "ping.py" in paths
    assert "pong.py" in paths
    root = next(f for f in files if f.path == "__init__.py")
    assert "from .ping import ping" in root.source
    assert "from .pong import pong" in root.source
    assert "Generated by adk-code-mode" in root.source


